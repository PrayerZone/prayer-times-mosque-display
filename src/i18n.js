export function translator(language) {
  const copy = TRANSLATIONS[language] ?? TRANSLATIONS.en;
  return (key) => copy[key] ?? EN[key] ?? key;
}

export function prayerName(language, id, fallback) {
  const key = String(id ?? "").toLowerCase();
  return TRANSLATIONS[language]?.prayerNames?.[key] ?? EN.prayerNames[key] ?? fallback ?? id;
}
